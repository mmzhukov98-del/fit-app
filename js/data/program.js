export let WHO = 'her';
export let WORKOUTS = HER_WORKOUTS;
export let ORDER = ['A', 'B', 'C'];
export let PHASES = HER_PHASES;
export let TOTAL_WEEKS = 10;
export let MODE = 'rotation';

export function useProgram(who) {
  const p = PROGRAMS[who] || PROGRAMS.her;
  WHO = PROGRAMS[who] ? who : 'her';
  WORKOUTS = p.WORKOUTS; ORDER = p.ORDER; PHASES = p.PHASES; TOTAL_WEEKS = p.TOTAL_WEEKS; MODE = p.MODE;
}

export function phaseForWeek(week) {
  const w = Math.min(Math.max(week, 1), TOTAL_WEEKS);
  return PHASES.find(p => w >= p.from && w <= p.to);
}

// План недели (только для режима weekly): список сессий с ключами
export function weekPlan(week) {
  if (MODE !== 'weekly') return null;
  const w = Math.min(Math.max(week, 1), TOTAL_WEEKS);
  return PROGRAMS[WHO].WEEKS[w].map(x => (typeof x === 'string' ? { k: x, kind: 'strength' } : x)).sort((a, b) => (a.day ?? 9) - (b.day ?? 9));
}

// Что стоит в расписании на день недели (0 = Пн) для недели программы week
export function scheduleForWeekday(wd, week) {
  if (MODE === 'weekly') return (weekPlan(Math.max(1, week)) || []).filter(p => p.day === wd);
  const k = Object.keys(HER_DAYS).find(key => HER_DAYS[key] === wd);
  return k ? [{ k, kind: 'strength', day: wd }] : [];
}

const RUN_COLORS = { run: '#ff9500', bike: '#34c759', mobility: '#5ac8fa' };
// Описание любой сессии по ключу (A/B/C или беговые E1/E2/Q/L/BK)
export function sessionInfo(key, week = 1) {
  if (WORKOUTS[key]) return WORKOUTS[key];
  const plan = weekPlan(week) || [];
  const r = plan.find(x => x.k === key) || (PROGRAMS.him.WEEKS[1].find(x => typeof x === 'object' && x.k === key));
  if (!r) return { id: key, kind: 'run', name: 'Кардио', color: RUN_COLORS.run, duration: 30, goal: '' };
  const minNum = parseInt(String(r.min), 10) || 30;
  return { id: key, kind: r.kind, name: r.name, color: r.quality ? '#ff375f' : RUN_COLORS[r.kind], duration: minNum, minText: r.min, goal: r.desc, optional: !!r.optional, quality: !!r.quality, long: !!r.long };
}

